import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';
import { buildCsp, cspEnabled, cspReportOnly } from './csp.js';

// Content Security Policy (see csp.js for the rules and the .env switches).
//  - Production build only. The dev server needs inline scripts / eval for hot
//    reload, so it is left alone.
//  - Enforcing mode: a <meta http-equiv> tag is written into dist/index.html, so it
//    works even if the web server adds no header.
//  - Always: dist/csp-nginx.conf, the same policy as a real HTTP header (it also
//    carries frame-ancestors and report-uri, which a <meta> tag cannot). Include it
//    in the nginx server block that serves the app:   include /path/to/dist/csp-nginx.conf;
//  - VITE_CSP_REPORT_ONLY=true: no <meta> (it can't be report-only); the nginx file
//    sends Content-Security-Policy-Report-Only instead, so nothing is blocked.
function cspPlugin(env) {
  return {
    name: 'app-csp',
    apply: 'build',
    transformIndexHtml() {
      if (!cspEnabled(env) || cspReportOnly(env)) return;
      return [
        {
          tag: 'meta',
          attrs: { 'http-equiv': 'Content-Security-Policy', content: buildCsp(env, { forMeta: true }) },
          injectTo: 'head-prepend',
        },
      ];
    },
    generateBundle() {
      if (!cspEnabled(env)) return;
      const header = cspReportOnly(env) ? 'Content-Security-Policy-Report-Only' : 'Content-Security-Policy';
      const policy = buildCsp(env).replace(/"/g, '\\"');
      this.emitFile({
        type: 'asset',
        fileName: 'csp-nginx.conf',
        source:
          `# Generated by the build (vite.config.js + csp.js). Include inside the nginx\n` +
          `# server block that serves the app. "always" also sends it on error pages.\n` +
          `add_header ${header} "${policy}" always;\n`,
      });
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = { ...loadEnv(mode, process.cwd(), 'VITE_'), ...Object.fromEntries(Object.entries(process.env).filter(([k]) => k.startsWith('VITE_'))) };

  return {
    plugins: [react(), cspPlugin(env)],
    server: {
      port: 5173,
      proxy: {
        '/api': {
          target: 'http://localhost:5000',
          changeOrigin: true,
          secure: true,
          // Live "saving…" updates: also forward WebSocket upgrades (/api/ws -> Express /ws)
          ws: true,
          // ADD THIS: Strips '/api' before sending to Express
          rewrite: (path) => path.replace(/^\/api/, '')
        },
      },
    },
    build: {
      outDir: 'dist',
      sourcemap: false,
      // Maintaining default 500kb limit by omitting chunkSizeWarningLimit
      rollupOptions: {
        output: {
          manualChunks(id) {
            if (id.includes('node_modules')) {
              const modulePath = id.split('node_modules/')[1];
              const packageName = modulePath.split('/')[0];

              if (packageName.startsWith('@')) {
                const subPackageName = modulePath.split('/')[1];
                return `${packageName.replace('@', '')}-${subPackageName}`;
              }

              return packageName;
            }
          }
        }
      }
    }
  };
});
